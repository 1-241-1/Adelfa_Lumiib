number1 = float(input("Enter a number: "))
number2 = float(input("Enter another number: "))

def calculate_sum():
    sum = (number1 + number2)
    print(f"Sum: {sum}")

def calculate_difference():
    difference = (number1 - number2)
    print(f"Difference: {difference}")

calculate_sum()
calculate_difference()
